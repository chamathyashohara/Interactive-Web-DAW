#pragma once

// Live media datagrams, header v1 (ADR-008, as built: ADR-017, PROTOCOL_OVERVIEW §12).
//
//  off size field
//   0   4   seq            per-stream packet counter, starts at 0, wraps at 2^32 (serial arithmetic)
//   4   8   mediaIndex    48 kHz live-stream sample counter of the first sample in the packet
//                          (includes samples dropped by a tap overflow, so such gaps are visible)
//  12   4   session_id     the 8-hex-digit session id as a u32 (never 0)
//  16   2   streamId      1 = producer microphone (producer -> performer)
//                          2 = performer microphone (performer -> producer, Stage 8)
//  18   2   payloadLen    must equal datagram length - 26
//  20   1   ver_type       high nibble = header version (1), low nibble = packet type
//  21   1   flags          AUDIO: bits 0-1 codec (1 = Opus), bit 2 = sender muted (payload is
//                          encoded silence; the stream keeps running); bits 3-7 reserved = 0
//  22   4   crc32          CRC-32/IEEE over bytes 0-21 and the payload (corruption only, not security)
//
// Big-endian. One datagram <= 1472 bytes (1500 MTU - IPv4 - UDP): no IP fragmentation.

#include <cstddef>
#include <cstdint>
#include <string>

constexpr size_t kMediaHeaderBytes = 26;
constexpr size_t kMaxDatagramBytes = 1472;
constexpr size_t kMaxPayloadBytes = kMaxDatagramBytes - kMediaHeaderBytes;  // 1446
constexpr uint8_t kHeaderVersion = 1;
constexpr uint16_t kStreamProducerMic = 1;
constexpr uint16_t kStreamPerformerMic = 2;
constexpr uint8_t kFlagMuted = 0x04;  // AUDIO only
constexpr uint8_t kCodecOpus = 1;

enum class PacketType : uint8_t
{
    Audio = 0,         // one Opus packet
    // 1, 2: PROBE_REQ / PROBE_RESP (designed in PROTOCOL_OVERVIEW §3.4, not implemented: rejected as bad_type)
    EndOfStream = 3,   // sender stops on purpose: receiver returns to filling without counting loss
    ReceiverReport = 4 // every 500 ms, about the stream in its streamId: sent by whoever RECEIVES
                       // that stream (performer about stream 1, producer about stream 2). The
                       // performer's reports also tell the producer where to send (ADR-017).
};

struct MediaHeader
{
    uint32_t seq = 0;
    uint64_t mediaIndex = 0;
    uint32_t sessionId = 0;
    uint16_t streamId = kStreamProducerMic;
    uint16_t payloadLen = 0;
    PacketType type = PacketType::Audio;
    uint8_t flags = 0;
};

/**
 * Validation result, in the order of the checks (PROTOCOL_OVERVIEW §2.1 steps 2-8; step 1, the
 * source address, is checked by the socket owner before calling parsePacket()).
 */
enum class PacketCheck : uint8_t
{
    Ok = 0,
    BadLength,     // < 26 bytes, > 1472 bytes, or payloadLen != length - 26
    BadVersion,    // header version nibble != 1
    BadType,       // unknown or unimplemented type
    BadCrc,
    BadSession,    // session id is not this session's
    BadPayload,    // type-specific: codec, reserved flag bits, payload size
};
const char* packetCheckName(PacketCheck c) noexcept;

/** Receive counters for rejected datagrams, one per reason (ERR-07). */
struct InvalidCounts
{
    uint64_t srcRejected = 0;  // not from the expected peer address
    uint64_t oversized = 0;     // larger than the receive buffer (Windows WSAEMSGSIZE)
    uint64_t badLength = 0;
    uint64_t badVersion = 0;
    uint64_t badType = 0;
    uint64_t badCrc = 0;
    uint64_t badSession = 0;
    uint64_t badPayload = 0;
    uint64_t wrongStream = 0;  // valid packet for a stream this side does not receive (e.g. its own
                                     /** stream coming back, or a report about a stream it does not send) */
    uint64_t total() const noexcept
    {
        return srcRejected + oversized + badLength + badVersion + badType + badCrc + badSession + badPayload +
               wrongStream;
    }
    void count(PacketCheck c) noexcept;
};

/** Receiver report payload (type 4), 64 bytes, big-endian. */
struct ReceiverReport
{
    static constexpr size_t kBytes = 64;
    static constexpr uint32_t kFlagPlaying = 1u << 0;  // performer has "hear the producer" on
    static constexpr uint32_t kFlagClosing = 1u << 1;  // performer stopped listening: stop sending
    uint64_t received = 0;        // valid audio packets (unique)
    uint64_t lostEstimate = 0;   // expected - received (from sequence numbers)
    uint32_t late = 0;            // arrived after their playout time
    uint32_t duplicates = 0;
    uint32_t reordered = 0;
    uint32_t jitterUs = 0;       // RFC 3550 inter-arrival jitter estimate
    uint32_t jbFill = 0;         // jitter-buffer occupancy (packets)
    uint32_t jbTarget = 0;
    uint32_t underruns = 0;
    uint32_t concealed = 0;       // frames generated by Opus PLC (lost + underrun)
    uint32_t decodeErrors = 0;
    uint32_t invalidPackets = 0;
    uint32_t flags = 0;
};

uint32_t crc32Ieee(const uint8_t* data, size_t size, uint32_t crc = 0) noexcept;

/**
 * Writes header + payload into `out` (>= kMediaHeaderBytes + payloadSize). Returns the datagram
 * size, or 0 if the payload is too large. Sets payloadLen and the CRC.
 */
size_t writePacket(const MediaHeader& header, const uint8_t* payload, size_t payloadSize,
                         uint8_t* out, size_t outSize) noexcept;

/**
 * Checks a received datagram (steps 2-8) without trusting any field before it is checked.
 * On Ok, `header` is filled and `payload` points into `data`.
 */
PacketCheck parsePacket(const uint8_t* data, size_t size, uint32_t expectedSession,
                         MediaHeader& header, const uint8_t*& payload) noexcept;

void writeReport(const ReceiverReport& r, uint8_t* out) noexcept;  // kBytes
ReceiverReport readReport(const uint8_t* in) noexcept;

/** "1a2b3c4d" -> 0x1a2b3c4d. False for anything that is not 8 lowercase hex digits or is 0. */
bool sessionIdToU32(const std::string& text, uint32_t& out) noexcept;

