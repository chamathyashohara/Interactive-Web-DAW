#pragma once

// Live media datagrams, header v1 (ADR-008, as built: ADR-017, PROTOCOL_OVERVIEW §12).
//
//  off size field
//   0   4   seq            per-stream packet counter, starts at 0, wraps at 2^32 (serial arithmetic)
//   4   8   media_index    48 kHz live-stream sample counter of the first sample in the packet
//                          (includes samples dropped by a tap overflow, so such gaps are visible)
//  12   4   session_id     the 8-hex-digit session id as a u32 (never 0)
//  16   2   stream_id      1 = producer microphone (the only stream in Stage 7)
//  18   2   payload_len    must equal datagram length - 26
//  20   1   ver_type       high nibble = header version (1), low nibble = packet type
//  21   1   flags          bits 0-1 codec (1 = Opus); bits 2-7 reserved, must be 0
//  22   4   crc32          CRC-32/IEEE over bytes 0-21 and the payload (corruption only, not security)
//
// Big-endian. One datagram <= 1472 bytes (1500 MTU - IPv4 - UDP): no IP fragmentation.

#include <cstddef>
#include <cstdint>
#include <string>

namespace rr::media {

constexpr std::size_t kHeaderBytes = 26;
constexpr std::size_t kMaxDatagramBytes = 1472;
constexpr std::size_t kMaxPayloadBytes = kMaxDatagramBytes - kHeaderBytes;  // 1446
constexpr std::uint8_t kHeaderVersion = 1;
constexpr std::uint16_t kStreamProducerMic = 1;
constexpr std::uint8_t kCodecOpus = 1;

enum class PacketType : std::uint8_t {
    Audio = 0,         // one Opus packet
    // 1, 2: PROBE_REQ / PROBE_RESP (designed in PROTOCOL_OVERVIEW §3.4, not implemented: rejected as bad_type)
    EndOfStream = 3,   // sender stops on purpose: receiver returns to filling without counting loss
    ReceiverReport = 4 // performer -> producer, every 500 ms: receive counters; also tells the
                       // producer where to send (address learning, ADR-017)
};

struct MediaHeader {
    std::uint32_t seq = 0;
    std::uint64_t media_index = 0;
    std::uint32_t session_id = 0;
    std::uint16_t stream_id = kStreamProducerMic;
    std::uint16_t payload_len = 0;
    PacketType type = PacketType::Audio;
    std::uint8_t flags = 0;
};

// Validation result, in the order of the checks (PROTOCOL_OVERVIEW §2.1 steps 2-8; step 1, the
// source address, is checked by the socket owner before calling parse_packet()).
enum class PacketCheck : std::uint8_t {
    Ok = 0,
    BadLength,     // < 26 bytes, > 1472 bytes, or payload_len != length - 26
    BadVersion,    // header version nibble != 1
    BadType,       // unknown or unimplemented type
    BadCrc,
    BadSession,    // session id is not this session's
    BadPayload,    // type-specific: codec, reserved flag bits, payload size
};
const char* packet_check_name(PacketCheck c) noexcept;

// Receive counters for rejected datagrams, one per reason (ERR-07).
struct InvalidCounts {
    std::uint64_t src_rejected = 0;  // not from the expected peer address
    std::uint64_t oversized = 0;     // larger than the receive buffer (Windows WSAEMSGSIZE)
    std::uint64_t bad_length = 0;
    std::uint64_t bad_version = 0;
    std::uint64_t bad_type = 0;
    std::uint64_t bad_crc = 0;
    std::uint64_t bad_session = 0;
    std::uint64_t bad_payload = 0;
    std::uint64_t total() const noexcept {
        return src_rejected + oversized + bad_length + bad_version + bad_type + bad_crc + bad_session + bad_payload;
    }
    void count(PacketCheck c) noexcept;
};

// Receiver report payload (type 4), 64 bytes, big-endian.
struct ReceiverReport {
    static constexpr std::size_t kBytes = 64;
    static constexpr std::uint32_t kFlagPlaying = 1u << 0;  // performer has "hear the producer" on
    static constexpr std::uint32_t kFlagClosing = 1u << 1;  // performer stopped listening: stop sending
    std::uint64_t received = 0;        // valid audio packets (unique)
    std::uint64_t lost_estimate = 0;   // expected - received (from sequence numbers)
    std::uint32_t late = 0;            // arrived after their playout time
    std::uint32_t duplicates = 0;
    std::uint32_t reordered = 0;
    std::uint32_t jitter_us = 0;       // RFC 3550 inter-arrival jitter estimate
    std::uint32_t jb_fill = 0;         // jitter-buffer occupancy (packets)
    std::uint32_t jb_target = 0;
    std::uint32_t underruns = 0;
    std::uint32_t concealed = 0;       // frames generated by Opus PLC (lost + underrun)
    std::uint32_t decode_errors = 0;
    std::uint32_t invalid_packets = 0;
    std::uint32_t flags = 0;
};

std::uint32_t crc32_ieee(const std::uint8_t* data, std::size_t size, std::uint32_t crc = 0) noexcept;

// Writes header + payload into `out` (>= kHeaderBytes + payload_size). Returns the datagram
// size, or 0 if the payload is too large. Sets payload_len and the CRC.
std::size_t write_packet(const MediaHeader& header, const std::uint8_t* payload, std::size_t payload_size,
                         std::uint8_t* out, std::size_t out_size) noexcept;

// Checks a received datagram (steps 2-8) without trusting any field before it is checked.
// On Ok, `header` is filled and `payload` points into `data`.
PacketCheck parse_packet(const std::uint8_t* data, std::size_t size, std::uint32_t expected_session,
                         MediaHeader& header, const std::uint8_t*& payload) noexcept;

void write_report(const ReceiverReport& r, std::uint8_t* out) noexcept;  // kBytes
ReceiverReport read_report(const std::uint8_t* in) noexcept;

// "1a2b3c4d" -> 0x1a2b3c4d. False for anything that is not 8 lowercase hex digits or is 0.
bool session_id_to_u32(const std::string& text, std::uint32_t& out) noexcept;

}  // namespace rr::media
